-- Dashboard Café: tabla inicial de ventas
-- Ejecuta este archivo en Supabase > SQL Editor > New query.
create table if not exists public.ventas_cafe (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  presentacion text not null check (presentacion in ('grano', 'molido')),
  tueste text not null check (tueste in ('claro', 'medio', 'oscuro')),
  gramos integer not null check (gramos in (250, 500, 1000)),
  cantidad integer not null check (cantidad > 0),
  total_mxn numeric(12,2) not null check (total_mxn > 0)
);

-- IMPORTANTE:
-- Para que la app funcione en esta primera prueba, habilita temporalmente
-- acceso anonimo desde Supabase con las politicas de abajo.
-- Esto NO es adecuado para producción: cualquier persona con la clave
-- pública podría leer/escribir ventas. Antes de publicar el negocio,
-- implementa Supabase Auth y políticas RLS por usuario.
alter table public.ventas_cafe enable row level security;

drop policy if exists "demo lectura ventas" on public.ventas_cafe;
drop policy if exists "demo insertar ventas" on public.ventas_cafe;

create policy "demo lectura ventas"
on public.ventas_cafe for select
to anon
using (true);

create policy "demo insertar ventas"
on public.ventas_cafe for insert
to anon
with check (true);
